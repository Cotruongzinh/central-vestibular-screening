const fragmentEn: Array<[string, string]> = [
  ['Hồ sơ/ca: ', 'Patient/case: '],
  ['Hồ sơ / ca: ', 'Patient / case: '],
  ['Tốc độ theo dõi (FPS): ', 'Tracking rate (FPS): '],
  ['Điểm đã lưu: ', 'Saved points: '],
  ['Điểm hiệu chỉnh: ', 'Calibration points: '],
  ['Mốc tư thế đầu:', 'Head baseline:'],
  ['Hoàn tất ', 'Completed '],
  ['mẫu', 'samples'],
  [' giây', ' sec'],
];

const exactVi: Record<string, string> = Object.fromEntries(
  Object.entries(exactEn).map(([vi, en]) => [en, vi]),
);

const fragmentVi: Array<[string, string]> = fragmentEn.map(([vi, en]) => [en, vi]);

export function translatePipelineText(language: AppLanguage, text: string): string {
  const exact = language === 'en' ? exactEn[text] : exactVi[text];
  if (exact) return exact;

  let translated = text;
  const fragments = language === 'en' ? fragmentEn : fragmentVi;
  for (const [from, to] of fragments) translated = translated.split(from).join(to);
  return translated;
}
